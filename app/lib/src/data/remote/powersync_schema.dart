import 'package:powersync/powersync.dart';

/// PowerSync client schema — local synced tables mirrored from Postgres (docs/04
/// §5, docs/13 §5.4). `id` is implicit (text PK). Booleans are stored as
/// integers; money/dates as text (docs/04 §3.4). Column names are snake_case to
/// match Drift's generated columns and the Postgres mirror.
const powersyncSchema = Schema([
  Table(
    'transactions',
    [
      Column.text('user_id'),
      Column.text('type'),
      Column.text('date'),
      Column.text('account_id'),
      Column.text('merchant_id'),
      Column.text('counter_account_id'),
      Column.text('currency_code'),
      Column.text('total_amount'),
      Column.text('base_amount'),
      Column.text('exchange_rate'),
      Column.text('tax_amount'),
      Column.text('note'),
      Column.text('source'),
      Column.text('status'),
      Column.text('created_at'),
      Column.text('updated_at'),
      Column.integer('deleted'),
      Column.integer('version'),
    ],
    indexes: [
      Index('tx_user_updated', [
        IndexedColumn.ascending('user_id'),
        IndexedColumn.ascending('updated_at'),
      ]),
      Index('tx_account', [IndexedColumn.ascending('account_id')]),
      // Date drives every analytics range filter (NFR-01, docs/04 §7).
      Index('tx_date', [IndexedColumn.ascending('date')]),
    ],
  ),
  Table(
    'line_items',
    [
      Column.text('user_id'),
      Column.text('transaction_id'),
      Column.text('description'),
      Column.text('quantity'),
      Column.text('unit_price'),
      Column.text('line_amount'),
      Column.text('category_id'),
      Column.text('tax_rate'),
      Column.real('ocr_confidence'),
      Column.integer('sort_order'),
      Column.text('updated_at'),
      Column.integer('deleted'),
      Column.integer('version'),
    ],
    indexes: [
      Index('li_transaction', [IndexedColumn.ascending('transaction_id')]),
      Index('li_category', [IndexedColumn.ascending('category_id')]),
    ],
  ),
  Table('categories', [
    Column.text('user_id'),
    Column.text('parent_id'),
    Column.text('name'),
    Column.text('kind'),
    Column.text('icon'),
    Column.text('color_hex'),
    Column.integer('is_archived'),
    Column.integer('sort_order'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('accounts', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('kind'),
    Column.text('currency_code'),
    Column.text('opening_balance'),
    Column.integer('is_archived'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('merchants', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('default_category_id'),
    Column.text('aliases'),
    Column.text('notes'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('tags', [
    Column.text('user_id'),
    Column.text('name'),
    Column.text('color_hex'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('line_item_tags', [
    Column.text('user_id'),
    Column.text('line_item_id'),
    Column.text('tag_id'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('exchange_rates', [
    Column.text('user_id'),
    Column.text('from_code'),
    Column.text('to_code'),
    Column.text('rate'),
    Column.text('date'),
    Column.text('source'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('settings', [
    Column.text('user_id'),
    Column.text('value'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table('categorization_rules', [
    Column.text('user_id'),
    Column.text('match_type'),
    Column.text('pattern'),
    Column.text('category_id'),
    Column.integer('priority'),
    Column.integer('is_enabled'),
    Column.text('updated_at'),
    Column.integer('deleted'),
    Column.integer('version'),
  ]),
  Table(
    'attachments',
    [
      Column.text('user_id'),
      Column.text('transaction_id'),
      Column.text('doc_type'),
      Column.text('file_name'),
      Column.text('storage_key'),
      Column.text('local_cache_path'),
      Column.text('enc_nonce'),
      Column.text('sha256'),
      Column.text('ocr_text'),
      Column.text('scan_status'),
      Column.integer('page_count'),
      Column.text('imported_at'),
      Column.text('updated_at'),
      Column.integer('deleted'),
      Column.integer('version'),
    ],
    indexes: [
      Index('att_transaction', [IndexedColumn.ascending('transaction_id')]),
      Index('att_sha256', [IndexedColumn.ascending('sha256')]),
    ],
  ),
  Table(
    'budgets',
    [
      Column.text('user_id'),
      Column.text('category_id'),
      Column.text('period'),
      Column.text('amount'),
      Column.text('currency_code'),
      Column.text('start_month'),
      Column.integer('is_active'),
      Column.text('updated_at'),
      Column.integer('deleted'),
      Column.integer('version'),
    ],
    indexes: [
      Index('budget_category', [IndexedColumn.ascending('category_id')]),
    ],
  ),
  Table(
    'recurring_templates',
    [
      Column.text('user_id'),
      Column.text('type'),
      Column.text('name'),
      Column.text('account_id'),
      Column.text('merchant_id'),
      Column.text('category_id'),
      Column.text('currency_code'),
      Column.text('amount'),
      Column.text('note'),
      Column.text('frequency'),
      Column.text('next_date'),
      Column.text('last_run_date'),
      Column.integer('is_active'),
      Column.text('updated_at'),
      Column.integer('deleted'),
      Column.integer('version'),
    ],
  ),
  Table(
    'merchant_templates',
    [
      Column.text('user_id'),
      Column.text('merchant_key'),
      Column.text('currency_code'),
      Column.text('doc_type'),
      Column.text('category_hints'),
      Column.integer('sample_count'),
      Column.text('updated_at'),
      Column.integer('deleted'),
      Column.integer('version'),
    ],
    indexes: [
      Index('mtpl_user_key', [
        IndexedColumn.ascending('user_id'),
        IndexedColumn.ascending('merchant_key'),
      ]),
    ],
  ),
  // Derived analytics cache, not synced: rebuilt locally (docs/11 §11).
  Table.localOnly('monthly_rollups', [
    Column.text('user_id'),
    Column.text('period_month'),
    Column.text('category_id'),
    Column.text('base_amount'),
  ]),
  // Shared reference data, not per-user: local-only, seeded on each device.
  Table.localOnly('currencies', [
    Column.text('symbol'),
    Column.integer('decimal_digits'),
    Column.text('name'),
  ]),
]);
